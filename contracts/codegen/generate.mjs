import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';
import ts from 'typescript';

const contractUrl = new URL('../openapi.json', import.meta.url);
const typesUrl = new URL('../../frontend/src/shared/api/generated/', import.meta.url);
const indexUrl = new URL('../API_OPERATIONS.md', import.meta.url);
const source = await readFile(contractUrl, 'utf8');
const contract = JSON.parse(source);

function checkReferences(value) {
  if (!value || typeof value !== 'object') return;
  if ('$ref' in value) {
    if (typeof value.$ref !== 'string' || !value.$ref.startsWith('#/')) {
      throw new Error(`Only local contract references are supported: ${value.$ref}`);
    }
    let target = contract;
    for (const token of value.$ref.slice(2).split('/')) {
      const key = token.replaceAll('~1', '/').replaceAll('~0', '~');
      if (!target || typeof target !== 'object' || !Object.hasOwn(target, key)) {
        throw new Error(`Unresolved contract reference: ${value.$ref}`);
      }
      target = target[key];
    }
  }
  for (const child of Object.values(value)) checkReferences(child);
}

checkReferences(contract);
const types = astToString(await openapiTS(contract, {
  transform(schema) {
    if (schema.type === 'string' && schema.format === 'binary') {
      return ts.factory.createTypeReferenceNode('Blob');
    }
  },
}));
const generated = `/** Generated by openapi-typescript. Do not edit. */\n\n${types}`;
const manifest = `${JSON.stringify({
  contract: 'contracts/openapi.json',
  contractVersion: contract.info.version,
  contractSha256: createHash('sha256').update(source).digest('hex'),
  generator: 'openapi-typescript@7.13.0',
  generatorCompiler: 'typescript@5.9.3',
  binaryRepresentation: 'Blob',
  outputSha256: createHash('sha256').update(generated).digest('hex'),
}, null, 2)}\n`;

function operationIndex() {
  const methods = new Set(['get', 'post', 'put', 'patch', 'delete', 'options', 'head']);
  const rows = [];
  for (const [path, item] of Object.entries(contract.paths)) {
    for (const [method, operation] of Object.entries(item)) {
      if (!methods.has(method)) continue;
      const scope = path.startsWith('/__mock__/') ? 'Development only' : path === '/health' ? 'Health' : 'Application';
      const success = Object.keys(operation.responses).filter((code) => /^2\d\d$/.test(code)).join(', ');
      rows.push(`| \`${operation.operationId}\` | ${method.toUpperCase()} | \`${path}\` | ${success} | ${scope} |`);
    }
  }
  return `# API operation index\n\nGenerated from [\`openapi.json\`](openapi.json) by \`codegen/generate.mjs\`. Do not edit the table independently. Contract version: ${contract.info.version}. The exact bodies, error schemas, authorization descriptions and parameters remain in OpenAPI.\n\n| Operation | Method | Path | Success | Scope |\n| --- | --- | --- | --- | --- |\n${rows.join('\n')}\n\nTotal documented operations: ${rows.length}. Development controls are not production application endpoints.\n`;
}

const outputs = [
  [new URL('schema.d.ts', typesUrl), generated],
  [new URL('manifest.json', typesUrl), manifest],
  [indexUrl, operationIndex()],
];
for (const [destination, expected] of outputs) {
  if (process.argv.includes('--check')) {
    const actual = await readFile(destination, 'utf8');
    if (actual !== expected) throw new Error(`Generated output is stale: ${destination.pathname}`);
  } else {
    await mkdir(new URL('./', destination), { recursive: true });
    await writeFile(destination, expected);
  }
}

console.log(process.argv.includes('--check') ? 'Generated files match the source contract.' : 'Generated types, contract hash and operation index written.');
